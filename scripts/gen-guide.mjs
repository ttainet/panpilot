#!/usr/bin/env node
/**
 * Generate src/guide.ts from docs/AI_DRIVER_GUIDE.md.
 *
 * The AI Driver guide lives in three places that must stay in sync:
 *   1. docs/AI_DRIVER_GUIDE.md  — the source of truth (edit this one)
 *   2. AGENTS.md (repo root)    — a hand-maintained concise summary
 *   3. GET /api/driver/agent-guide — served by the Worker from src/guide.ts,
 *      which this script generates from (1). Run `npm run gen:guide`
 *      after editing the guide, and commit both files.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const md = readFileSync(join(root, "docs", "AI_DRIVER_GUIDE.md"), "utf8");

const out = `/**
 * GENERATED by scripts/gen-guide.mjs from docs/AI_DRIVER_GUIDE.md — do not
 * edit this file directly. Edit the guide, run \`npm run gen:guide\`, and
 * commit both files. The same guide is summarized in the repo-root
 * AGENTS.md and served verbatim by GET /api/driver/agent-guide.
 */
export const AI_DRIVER_GUIDE_MD = ${JSON.stringify(md)};
`;

writeFileSync(join(root, "src", "guide.ts"), out);
console.log(`[gen-guide] src/guide.ts written (${md.length} chars from docs/AI_DRIVER_GUIDE.md)`);
